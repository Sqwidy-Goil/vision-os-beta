    func testRejectsTamperingReplayAndOversizeFrames() throws {
        let frame = try CompanionFrameCodec.encode(
            sid: sid,
            sequence: 3,
            sentAt: 1000,
            type: .sample,
            payload: sample().dictionary(),
            options: CompanionFrameCodec.EncodeOptions(key: key())
        )
        var tampered = frame
        tampered[tampered.count - 1] ^= 1
        XCTAssertThrowsError(try CompanionFrameCodec.decode(
            tampered,
            options: CompanionFrameCodec.DecodeOptions(key: key(), now: 1000)
        )) { error in
            XCTAssertTrue(error.localizedDescription.contains("authentication"))
        }
        XCTAssertThrowsError(try CompanionFrameCodec.decode(
            frame,
            options: CompanionFrameCodec.DecodeOptions(key: key(), expectedSequence: 2, now: 1000)
        ))
        XCTAssertThrowsError(try CompanionFrameCodec.decode(
            Data(count: CompanionProtocol.defaultMaxFrameBytes + 1),
            options: CompanionFrameCodec.DecodeOptions(key: key(), now: 1000)
        ))
    }

    func testBase64DepthAndGzipFallbacks() throws {
        let base64Frame = try CompanionFrameCodec.encode(
            sid: sid,
            sequence: 4,
            sentAt: 1000,
            type: .sample,
            payload: sample().dictionary(depthEncoding: .base64),
            options: CompanionFrameCodec.EncodeOptions(key: key(), depthEncoding: .base64)
        )
        let base64 = try CompanionFrameCodec.decode(
            base64Frame,
            options: CompanionFrameCodec.DecodeOptions(key: key(), now: 1000)
        )
        XCTAssertEqual(base64.header.depthEncoding, .base64)
        XCTAssertTrue(base64.depthChunk.isEmpty)
        let depth = try XCTUnwrap(base64.payload["depth"] as? [String: Any])
        XCTAssertTrue(depth["values"] is String)
        XCTAssertTrue(depth["confidence"] is String)

        let compressed = try CompanionFrameCodec.encode(
            sid: sid,
            sequence: 5,
            sentAt: 1000,
            type: .sample,
            payload: sample().dictionary(),
            options: CompanionFrameCodec.EncodeOptions(key: key(), compression: true)
        )
        let decoded = try CompanionFrameCodec.decode(
            compressed,
            options: CompanionFrameCodec.DecodeOptions(key: key(), now: 1000)
        )
        XCTAssertEqual(decoded.header.payloadEncoding, .gzip)
    }

    func testGzipDecompressionIsBounded() throws {
        let compressed = try XCTUnwrap(CompanionGzip.compress(Data(repeating: 65, count: 10_000)))
        XCTAssertThrowsError(try CompanionGzip.decompress(compressed, limit: 100))
        let output = try CompanionGzip.decompress(compressed, limit: 10_000)
        XCTAssertEqual(output.count, 10_000)
    }

