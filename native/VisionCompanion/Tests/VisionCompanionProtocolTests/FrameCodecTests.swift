import Foundation
import XCTest
@testable import VisionCompanionProtocol

final class FrameCodecTests: XCTestCase {
    private let sid = "AAAAAAAAAAAAAAAAAAAAAA"

    private func key() -> SessionKey {
        SessionKey(bytes: Data(repeating: 9, count: 32))
    }

    private func sample(timestamp: Double = 1000) -> SpatialUpdateWire {
        var covariance = [Double](repeating: 0, count: 36)
        covariance[0] = covariance[7] = covariance[14] = 0.01
        covariance[21] = covariance[28] = covariance[35] = 0.0004
        return SpatialUpdateWire(
            frameId: 1,
            timestamp: timestamp,
            baseFrameId: 0,
            reset: true,
            calibrationId: "cal-1",
            pose: .full(PoseWire(
                position: [0, 0, 0],
                quaternion: [0, 0, 0, 1],
                velocity: [0, 0, 0],
                covariance: covariance,
                confidence: 0.9
            )),
            calibrationConfidence: 0.85,
            depth: DepthUpdateWire(
                mode: .full,
                width: 2,
                height: 2,
                intrinsics: CameraIntrinsicsWire(width: 2, height: 2, fx: 2, fy: 2, cx: 1, cy: 1, timestamp: timestamp),
                values: [0, 1, 2, 3],
                confidence: [0, 0.9, 0.8, 0.7]
            ),
            surfaces: [],
            objects: [],
            freeSpace: [],
            removed: nil
        )
    }

    func testRoundTripsBinaryDepthAndAuthentication() throws {
        let source = sample()
        let frame = try CompanionFrameCodec.encode(
            sid: sid,
            sequence: 3,
            sentAt: 1000,
            type: .sample,
            payload: source.dictionary(),
            options: CompanionFrameCodec.EncodeOptions(key: key())
        )
        let decoded = try CompanionFrameCodec.decode(
            frame,
            options: CompanionFrameCodec.DecodeOptions(key: key(), expectedSID: sid, expectedSequence: 3, now: 1000)
        )
        XCTAssertEqual(decoded.header.payloadEncoding, .identity)
        XCTAssertEqual(decoded.header.depthEncoding, .float32le)
        XCTAssertEqual(decoded.depthChunk.count, 32)
        let values = decoded.depthChunk.withUnsafeBytes { buffer in
            (0..<4).map { index in
                Float(bitPattern: UInt32(
                    littleEndian: buffer.loadUnaligned(
                        fromByteOffset: index * 4,
                        as: UInt32.self
                    )
                ))
            }
        }
        XCTAssertEqual(values, [0, 1, 2, 3])
    }

